// 답 비교 — 공백·대소문자를 무시하고, 곱셈기호나 흔한 표기 차이를 흡수한다
export function checkAnswer(input, answer) {
  const norm = (s) =>
    String(s)
      .trim()
      .toLowerCase()
      .replace(/\s+/g, '')
      .replace(/[*×]/g, '')
      .replace(/root3|sqrt3/g, '√3')
  return norm(input) === norm(answer)
}
